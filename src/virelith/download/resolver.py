def fail(msg):
    raise SystemExit(f"uup-fetch: {msg}")


def rand_hex(n):
    return "".join(random.choice("0123456789abcdef") for _ in range(n))


def device_ticket():
    """Fabricated (non-attested) Windows Update device ticket, exactly as
    generated by the reference UUP client implementations."""
    header = "13003002c377040014d5bcac7a66de0d50beddf9bba16c87edb9e019898000"
    t = base64.b64encode(bytes.fromhex(header + rand_hex(1054) + "b401")).decode()
    return base64.b64encode("\0".join("t=" + t + "&p=").encode()).decode()


