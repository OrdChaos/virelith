#!/usr/bin/env python3
"""Resolve and download one fixed Windows Update payload.

Fixed inputs (argv): Windows Update update ID, payload file ID (GUID),
payload file name, payload size in bytes, payload SHA-1 digest.

The Microsoft Windows Update service (anonymous SOAP, no account) returns a
short-lived signed CDN URL for the requested update; the bytes are then
downloaded from the Microsoft CDN.  The Guix daemon enforces the package's
fixed-output hash; this script only checks the WU-side identity (digest,
file GUID, size) and fails closed on anything unexpected.

No fallbacks: a fixed source that cannot be fetched is a fetch failure.
"""

