print(f"uup-fetch: ssl cert file={bundle_path!r} "
      f"dir={os.environ.get('SSL_CERT_DIR')!r}", flush=True)
if bundle_path:
    print(f"uup-fetch: bundle exists={os.path.isfile(bundle_path)} "
          f"size={os.path.getsize(bundle_path) if os.path.isfile(bundle_path) else 0}",
          flush=True)
print(f"uup-fetch: verify paths={ssl.get_default_verify_paths()}", flush=True)

