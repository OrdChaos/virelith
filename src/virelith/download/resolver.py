def uuid4():
    return "%08x-%04x-%04x-%04x-%04x%08x" % (
        random.getrandbits(32), random.getrandbits(16),
        random.getrandbits(16) | 0x4000, random.getrandbits(16) | 0x8000,
        random.getrandbits(32), random.getrandbits(32))


def envelope(action, to, body):
    now = int(time.time())
    return f"""<s:Envelope xmlns:a="http://www.w3.org/2005/08/addressing" xmlns:s="http://www.w3.org/2003/05/soap-envelope">
<s:Header>
<a:Action s:mustUnderstand="1">{action}</a:Action>
<a:MessageID>urn:uuid:{uuid4()}</a:MessageID>
<a:To s:mustUnderstand="1">{to}</a:To>
<o:Security s:mustUnderstand="1" xmlns:o="http://docs.oasis-open.org/wss/2004/01/oasis-200401-wss-wssecurity-secext-1.0.xsd">
<Timestamp xmlns="http://docs.oasis-open.org/wss/2004/01/oasis-200401-wss-wssecurity-utility-1.0.xsd">
<Created>{w3c(now)}</Created>
<Expires>{w3c(now+120)}</Expires>
</Timestamp>
<wuws:WindowsUpdateTicketsToken wsu:id="ClientMSA" xmlns:wsu="http://docs.oasis-open.org/wss/2004/01/oasis-200401-wss-wssecurity-utility-1.0.xsd" xmlns:wuws="http://schemas.microsoft.com/msus/2014/10/WindowsUpdateAuthorization">
<TicketType Name="MSA" Version="1.0" Policy="MBI_SSL">
<Device>{device_ticket()}</Device>
</TicketType>
</wuws:WindowsUpdateTicketsToken>
</o:Security>
</s:Header>
<s:Body>{body}</s:Body>
</s:Envelope>"""


def post(url, xml):
    """HTTPS POST with normal TLS verification: the builder sets
    SSL_CERT_FILE/SSL_CERT_DIR (standard CA bundle + pinned Microsoft CAs)."""
    req = urllib.request.Request(
        url, data=xml.encode(),
        headers={"User-Agent": USER_AGENT,
                 "Content-Type": "application/soap+xml; charset=utf-8"})
    with urllib.request.urlopen(req, timeout=120) as resp:
        return resp.read().decode("utf-8", "replace")


def get_cookie():
    now = w3c(int(time.time()))
    body = f"""<GetCookie xmlns="http://www.microsoft.com/SoftwareDistribution/Server/ClientWebService">
<oldCookie><Expiration>{now}</Expiration></oldCookie>
<lastChange>{now}</lastChange>
<currentTime>{now}</currentTime>
<protocolVersion>2.0</protocolVersion>
</GetCookie>"""
    out = post(FE3, envelope(
        "http://www.microsoft.com/SoftwareDistribution/Server/ClientWebService/GetCookie",
        FE3, body))
    root = ET.fromstring(out)
    for el in root.iter():
        if el.tag.rsplit("}", 1)[-1] == "EncryptedData" and el.text:
            return el.text.strip()
    fail("GetCookie: no EncryptedData in response")


def get_file_locations(cookie):
    now = w3c(int(time.time()))
    body = f"""<GetExtendedUpdateInfo2 xmlns="http://www.microsoft.com/SoftwareDistribution/Server/ClientWebService">
<updateIDs>
<UpdateIdentity><UpdateID>{UPDATE_ID}</UpdateID><RevisionNumber>1</RevisionNumber></UpdateIdentity>
</updateIDs>
<infoTypes>
<XmlUpdateFragmentType>FileUrl</XmlUpdateFragmentType>
<XmlUpdateFragmentType>FileDecryption</XmlUpdateFragmentType>
<XmlUpdateFragmentType>EsrpDecryptionInformation</XmlUpdateFragmentType>
<XmlUpdateFragmentType>PiecesHashUrl</XmlUpdateFragmentType>
<XmlUpdateFragmentType>BlockMapUrl</XmlUpdateFragmentType>
</infoTypes>
<deviceAttributes>{device_attributes()}</deviceAttributes>
<cookie><Expiration>{w3c(int(time.time())+3600)}</Expiration><EncryptedData>{cookie}</EncryptedData></cookie>
</GetExtendedUpdateInfo2>"""
    out = post(FE3_SECURED, envelope(
        "http://www.microsoft.com/SoftwareDistribution/Server/ClientWebService/GetExtendedUpdateInfo2",
        FE3_SECURED, body))
    root = ET.fromstring(out)
    locations = []
    for el in root.iter():
        if el.tag.rsplit("}", 1)[-1] != "FileLocation":
            continue
        digest = url = None
        for child in el:
            name = child.tag.rsplit("}", 1)[-1]
            if name == "FileDigest":
                digest = (child.text or "").strip()
            elif name == "Url":
                url = html.unescape((child.text or "").strip())
        if digest and url:
            locations.append((base64.b64decode(digest).hex(), url))
    if not locations:
        fail("GetExtendedUpdateInfo2: no FileLocations in response")
    return locations


def main():
    cookie = get_cookie()
    locations = get_file_locations(cookie)

    url = None
    for digest, candidate in locations:
        if digest == EXPECTED_SHA1:
            url = candidate
            break
    if url is None:
        fail(f"file digest {EXPECTED_SHA1} not among "
             f"{len(locations)} FileLocations")

    # The signed URL embeds the content-addressed file GUID.
    if re.search(r"/files/" + re.escape(FILE_ID) + r"(?:\?|$)", url) is None:
        fail(f"URL file ID mismatch: {FILE_ID} not in {url[:120]}")

    print(f"uup-fetch: resolved {FILE_NAME} ({EXPECTED_SIZE} B, "
          f"sha1 {EXPECTED_SHA1}) -> {url[:90]}...", flush=True)

    with urllib.request.urlopen(url, timeout=600) as resp:
        data = resp.read()
    if len(data) != EXPECTED_SIZE:
        fail(f"size mismatch: expected {EXPECTED_SIZE}, got {len(data)}")
    with open(OUTPUT, "wb") as f:
        f.write(data)
    print(f"uup-fetch: downloaded {len(data)} bytes to {OUTPUT}", flush=True)


if __name__ == "__main__":
    main()
